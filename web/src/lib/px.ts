export function pxPath(rows: string[]): string {
  let d = ''
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== '#') { x++; continue }
      let e = x
      while (row[e] === '#') e++
      d += `M${x} ${y}h${e - x}v1h-${e - x}z`
      x = e
    }
  })
  return d
}
