// Freeze the supplied pixel art without reimplementing its drawing algorithm.
// Run from the repo root: node web/scripts/export_wiskit.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { runInNewContext } from 'node:vm'

const source = new URL('../../assets-source/wiskit/drawing.js', import.meta.url)
const code = readFileSync(source, 'utf8')
if (!code?.includes('const STATES=')) throw new Error('Wiskit reference drawing section missing')
const art = runInNewContext(`${code}; ({palette:P, states: Object.fromEntries(Object.entries(STATES).map(([name,s]) => [name, {ms:s.ms, move:s.move || [], frames:s.frames.map(g => g.map(r => r.join('')))}]))})`, {}, { timeout: 10000 })
for (const s of Object.values(art.states)) {
  if (!s.frames.length || !s.frames.every(g => g.length === 56 && g.every(r => r.length === 96 && [...r].every(c => c === '.' || art.palette[c])))) throw new Error('Invalid Wiskit frame')
}
const target = new URL('../../desktop/wiskit_art.py', import.meta.url)
const output = '# Generated by web/scripts/export_wiskit.mjs from assets-source/wiskit/drawing.js.\n' +
  `PALETTE = ${JSON.stringify(art.palette)}\nSTATES = ${JSON.stringify(art.states)}\n`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Wiskit art is stale; run node web/scripts/export_wiskit.mjs')
} else writeFileSync(target, output)
console.log(`Exported ${Object.keys(art.states).length} Wiskit stances`)
