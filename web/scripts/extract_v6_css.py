"""Generate web/public/styles from assets-source/styles; --check writes nothing.

Run from web/: py scripts/extract_v6_css.py (npm run css).
"""
import argparse
from pathlib import Path

WEB = Path(__file__).resolve().parent.parent
SOURCE = WEB.parent / 'assets-source' / 'styles'
OUT = WEB / 'public' / 'styles'
HEADER = '/* GENERATED by web/scripts/extract_v6_css.py from assets-source/styles. Do not edit. */\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    for name in ('v6-page.css', 'v6-cards-theme.css'):
        body = (SOURCE / name).read_text(encoding='utf-8').replace('\r\n', '\n').replace('\r', '\n')
        output = HEADER + body.strip() + '\n'
        path = OUT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != output:
                raise SystemExit(f'{name} is stale; run npm run css in web/')
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(output, encoding='utf-8', newline='\n')
        print(f'{name}: {len(body):,} chars' + (' checked' if args.check else ' generated'))


if __name__ == '__main__':
    main()
